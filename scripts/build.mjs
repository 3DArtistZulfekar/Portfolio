import {cp,mkdir,rm,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const dist=new URL('../dist/',import.meta.url);
await rm(dist,{recursive:true,force:true});await mkdir(dist,{recursive:true});
for(const file of ['index.html','models.html','model.html','admin.html','assets','data'])await cp(root+file,new URL(file,dist),{recursive:true});
await mkdir(new URL('css/',dist),{recursive:true});
for(const file of ['portfolio.css','studio.css'])await cp(root+'css/'+file,new URL('css/'+file,dist));
await mkdir(new URL('js/',dist),{recursive:true});
for(const file of ['viewer.js','shared.js','portfolio.js','gallery.js','model-page.js','github.js','studio'])await cp(root+'js/'+file,new URL('js/'+file,dist),{recursive:true});
await writeFile(new URL('.nojekyll',dist),'');
console.log('Built dist/ — static portfolio ready for GitHub Pages.');
